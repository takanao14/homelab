#!/bin/bash
set -euo pipefail

GREEN='\033[0;32m'
YELLOW='\033[1;33m'
NC='\033[0m'

CONTAINERD_DIR="/etc/k0s/containerd.d"
CERTS_DIR="/etc/k0s/certs.d/docker.io"
REGISTRY_FILE="${CONTAINERD_DIR}/registry-path.toml"
HOSTS_FILE="${CERTS_DIR}/hosts.toml"
MIRROR_ENDPOINT="https://mirror.gcr.io"

preflight_checks() {
    echo -e "${YELLOW}→${NC} Checking prerequisites..."

    if ! sudo -n true 2>/dev/null; then
        echo -e "${YELLOW}→${NC} Authenticating with sudo..."
        sudo true
    fi

    echo -e "${GREEN}✓${NC} Prerequisites met"
}

create_directories() {
    local containerd_dir="$1"
    local certs_dir="$2"

    if [ ! -d "$containerd_dir" ]; then
        echo -e "${YELLOW}→${NC} Creating $containerd_dir..."
        sudo mkdir -p "$containerd_dir"
    else
        echo -e "${GREEN}✓${NC} $containerd_dir exists"
    fi

    if [ ! -d "$certs_dir" ]; then
        echo -e "${YELLOW}→${NC} Creating $certs_dir..."
        sudo mkdir -p "$certs_dir"
    else
        echo -e "${GREEN}✓${NC} $certs_dir exists"
    fi
}

configure_registry() {
    local registry_file="$1"
    local certs_base_path="/etc/k0s/certs.d"

    # containerd 2.x requires config v3 and the v2 CRI namespace.
    echo -e "${YELLOW}→${NC} Writing registry configuration..."
    sudo tee "$registry_file" > /dev/null <<EOF
version = 3

[plugins."io.containerd.cri.v1.images".registry]
  config_path = "$certs_base_path"
EOF
    echo -e "${GREEN}✓${NC} Registry configured at $registry_file"
}

render_hosts() {
    local mirror_endpoint="$1"
    cat <<EOF
server = "https://registry-1.docker.io"

[host."${mirror_endpoint}"]
  capabilities = ["pull", "resolve"]
EOF
}

configure_hosts() {
    local hosts_file="$1"
    local mirror_endpoint="$2"

    if sudo test -e "$hosts_file" || sudo test -L "$hosts_file"; then
        # Only replace the unmodified configuration generated by the original hook.
        if sudo test -L "$hosts_file" || ! sudo test -f "$hosts_file" ||
            ! render_hosts "https://mirror.gcr.io" | sudo cmp -s "$hosts_file" -; then
            echo -e "${YELLOW}→${NC} Preserving existing docker.io hosts configuration at $hosts_file"
            return
        fi
        if render_hosts "$mirror_endpoint" | sudo cmp -s "$hosts_file" -; then
            echo -e "${GREEN}✓${NC} docker.io hosts configuration is up to date"
            return
        fi
    fi

    echo -e "${YELLOW}→${NC} Writing docker.io hosts configuration..."
    render_hosts "$mirror_endpoint" | sudo tee "$hosts_file" > /dev/null
    echo -e "${GREEN}✓${NC} docker.io hosts configuration written to $hosts_file"
}

echo -e "${GREEN}=== Mirror Setup Script ===${NC}"
preflight_checks
create_directories "$CONTAINERD_DIR" "$CERTS_DIR"
configure_registry "$REGISTRY_FILE"
configure_hosts "$HOSTS_FILE" "$MIRROR_ENDPOINT"

echo -e "${GREEN}✓${NC} Setup completed successfully"
echo -e "${GREEN}✓${NC} Config directory: $CERTS_DIR"
